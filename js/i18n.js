// Get current saved language (default 'en' with instant toggle to 'hi')
export function getCurrentLang() {
  return localStorage.getItem("asc_lang") || "en";
}

// Translate key with fallback
export function t(key, replacements = {}) {
  const lang = getCurrentLang();
  let str = (translations[lang] && translations[lang][key]) || (translations.en && translations.en[key]) || key;
  for (const [k, v] of Object.entries(replacements)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

// Apply translations across all marked elements in the current DOM
export function applyTranslations() {
  const lang = getCurrentLang();
  const dict = translations[lang] || translations.en;

  // 1. Elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // 2. Elements with data-i18n-html
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // 3. Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // 4. Update language toggle button labels
  const langButtons = document.querySelectorAll(".lang-toggle-btn");
  langButtons.forEach(btn => {
    if (btn.classList.contains("lang-toggle-btn-drawer")) {
      btn.innerHTML = lang === "hi" ? `<span style="font-size: 18px;">🌐</span> <span>Switch to English</span>` : `<span style="font-size: 18px;">🌐</span> <span>हिंदी में देखें</span>`;
    } else {
      btn.innerHTML = `🌐`;
    }
    btn.title = lang === "hi" ? "Switch to English / हिंदी" : "हिंदी / English";
    btn.setAttribute("aria-label", "Switch Language");
  });

  // 5. Update HTML lang attribute
  document.documentElement.lang = lang;

  // 6. Dispatch custom event for dynamic modules
  window.dispatchEvent(new CustomEvent("asc-lang-changed", { detail: { lang } }));
}

// Toggle language
export function toggleLanguage() {
  const current = getCurrentLang();
  const next = current === "en" ? "hi" : "en";
  localStorage.setItem("asc_lang", next);
  applyTranslations();
  return next;
}

// Initialize Language Switcher Buttons
export function initLanguageSwitcher() {
  applyTranslations();

  document.querySelectorAll(".lang-toggle-btn").forEach(btn => {
    btn.addEventListener("click", (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });
}

